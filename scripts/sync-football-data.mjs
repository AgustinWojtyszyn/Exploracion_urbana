const headers={Accept:'application/vnd.github+json','User-Agent':'leyenda-data-sync'}

async function json(url){
  const res=await fetch(url,{headers})
  if(!res.ok) throw new Error(`${res.status} ${url}`)
  return res.json()
}

async function text(url){
  const res=await fetch(url,{headers})
  if(!res.ok) throw new Error(`${res.status} ${url}`)
  return res.text()
}

function seasonWeight(segment){
  const nums=segment.match(/\d{4}/g)?.map(Number)??[]
  return nums.length?Math.max(...nums):0
}

function teamsFromMatches(data){
  return [...new Set((data.matches??[]).flatMap(m=>[m.team1,m.team2]).filter(Boolean))]
}

function safeId(value){
  return value.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'')
}

async function main(){
  console.log('LEYENDA · sincronizando datos CC0 de OpenFootball…')
  const tree=await json(`${API}/repos/${OWNER}/${REPO}/git/trees/${BRANCH}?recursive=1`)
  const files=(tree.tree??[]).filter(x=>x.type==='blob'&&/^[^/]+\/[a-z]{2}\.([123])\.json$/.test(x.path))

  const candidates=new Map()
  for(const file of files){
    const match=file.path.match(/^([^/]+)\/([a-z]{2})\.([123])\.json$/)
    if(!match) continue
    const [,season,code,divisionRaw]=match
    if(!COUNTRY_NAMES[code]) continue
    const division=Number(divisionRaw)
    const key=`${code}-${division}`
    const candidate={path:file.path,season,code,division,weight:seasonWeight(season)}
    const prev=candidates.get(key)
    if(!prev||candidate.weight>prev.weight||(candidate.weight===prev.weight&&candidate.season>prev.season)){
      candidates.set(key,candidate)
    }
  }

  const grouped=new Map()
  for(const item of candidates.values()){
    const url=`${RAW}/${OWNER}/${REPO}/${BRANCH}/${item.path}`
    try{
      const data=JSON.parse(await text(url))
      const teams=teamsFromMatches(data)
      if(teams.length<6) continue
      const entry={id:`${item.code}-${item.division}`,country:COUNTRY_NAMES[item.code],division:item.division,teams,source:item.path}
      const rows=grouped.get(item.code)??[]
      rows.push(entry)
      grouped.set(item.code,rows)
    }catch(error){
      console.warn('skip',item.path,String(error))
    }
  }

  const complete=[...grouped.entries()]
    .map(([code,rows])=>({code,rows:rows.sort((a,b)=>a.division-b.division)}))
    .filter(group=>group.rows.some(r=>r.division===1))
    .sort((a,b)=>COUNTRY_NAMES[a.code].localeCompare(COUNTRY_NAMES[b.code],'es'))

  const all=complete.flatMap(x=>x.rows)
  const countries=new Set(all.map(x=>x.country))
  const multiDivision=complete.filter(x=>x.rows.length>=2).length

  const header=`// AUTO-GENERATED by scripts/sync-football-data.mjs
// Source: openfootball/football.json (public domain / CC0)
// League display names are deliberately generic in LEYENDA.
// Club crests are generated by LEYENDA and are NOT official marks.

export type LeagueSeed = { id:string; country:string; division:number; teams:string[]; source?:string }

export const verifiedLeagueSeeds:LeagueSeed[] = `
  const body=JSON.stringify(all,null,2)
  const footer=`

export const sourceNotice='Club names sourced from OpenFootball public-domain datasets. LEYENDA uses generic league labels and original generated crests; no official league branding or crests are bundled.'

export const dataCoverage={
  countries:${countries.size},
  leagues:${all.length},
  multiDivisionCountries:${multiDivision},
  generatedAt:${JSON.stringify(new Date().toISOString())}
}
`

  await fs.mkdir(path.dirname(OUT),{recursive:true})
  await fs.writeFile(OUT,header+body+footer,'utf8')
  console.log(`✓ ${countries.size} países · ${all.length} divisiones · ${multiDivision} países con 2+ divisiones verificadas`)
  console.log('✓',OUT)
}

